"""Can the model produce a BETTER spread than copying, when it only has to do that?

Take real corpus teams (composition fixed). Three spreads per team, paired:
  tuned     the team's own spreads, as played                     (ceiling)
  copied    random corpus spreads of the same species             (what earlier models did)
  steered   the 36 spread columns regenerated by the model, all other columns held,
            conditioned on the top win-rate bin at guidance 4, budget-constrained
Pre-registered: steered < tuned by several points; steered ~ copied. If steered > copied
the spread upgrade delivers a positive win-rate difference; if not, it is settled.
"""
import json, sys, time
from collections import defaultdict
from pathlib import Path
import numpy as np, torch, torch.nn.functional as F
sys.path.insert(0, "/tmp/vgc-pilot/src")
from corpus import norm, STATS
from encode import canon, NSLOT
import legaldiffusion as LD, spreaddiffusion as S, diffusion as D
from wrdiffusion import WNULL
from propose import Validator, slot_to_text
import pool

STAT_COLS = [c for c in range(S.COLS2) if c % S.NF2 >= 8]

@torch.no_grad()
def fill_spreads(model, C, x0, wbin=5, g_wr=4.0, device=LD.DEV):
    """Regenerate only the spread columns of x0 (batch), constrained, with win-rate CFG."""
    n = x0.shape[0]; x = x0.clone().to(device); x[:, STAT_COLS] = 0
    y = torch.full((n,), D.STYLES.index("none"), device=device, dtype=torch.long); yN = torch.full_like(y, D.NULL)
    w = torch.full((n,), wbin, device=device, dtype=torch.long); wN = torch.full_like(w, WNULL)
    gN = torch.full((n,), LD.LEG_NULL, device=device, dtype=torch.long)
    seq = [c for c in S.ORDER2 if c in STAT_COLS]
    for step, c in enumerate(seq):
        t_now = 0.45 * (1 - step / len(seq)); tt = torch.full((n,), t_now, device=device)
        lu = F.log_softmax(model.logits(model(x, tt, yN, wN, gN), c), -1)
        lw = F.log_softmax(model.logits(model(x, tt, y, w, gN), c), -1); l = lu + g_wr * (lw - lu)
        for b in range(n):
            ok = C.mask_for(c, x[b], device); lb = l[b].clone(); lb[~ok] = -1e9
            x[b, c] = torch.multinomial(torch.softmax(lb, -1), 1).item()
    return x

def main():
    n_teams = int(sys.argv[1]) if len(sys.argv) > 1 else 150
    m, V, L, corpus, teams = LD.load_model(); C = S.SpreadConstraints(V, L)
    spreads = defaultdict(list); look = {}
    for t in corpus:
        for s in t: spreads[norm(s["species"])].append(dict(s["evs"]))
    for t in corpus + teams:
        for s in t:
            look[norm(s["species"])] = s["species"]; look[norm(s["ability"])] = s["ability"]
            if s["item"]: look[norm(s["item"])] = s["item"]
            for mv in s["moves"]: look[norm(mv)] = mv
            if s["nature"]: look[norm(s["nature"])] = s["nature"]
    rng = np.random.default_rng(0); torch.manual_seed(0)
    pick = rng.choice(len(corpus), n_teams, replace=False)
    out = Path("/tmp/vgc-pilot/steer_gen"); out.mkdir(exist_ok=True)
    for f in out.glob("*.txt"): f.unlink()
    val = Validator(); triples = []
    for i0 in range(0, n_teams, 24):
        idx = pick[i0:i0 + 24]; base = [canon(corpus[i]) for i in idx]
        X0 = torch.tensor(np.stack([V.encode(corpus[i]) for i in idx]))
        Xs = fill_spreads(m, C, X0).cpu().numpy()
        for k, i in enumerate(idx):
            tuned = [dict(s) for s in base[k]]
            copied = [dict(s) for s in base[k]]
            for s in copied:
                pl = spreads.get(norm(s["species"])); s["evs"] = dict(pl[int(rng.integers(0, len(pl)))]) if pl else s["evs"]
            steered = [dict(s) for s in base[k]]
            gen = S.row_to_slots(V, Xs[k], look)
            for s, gs in zip(steered, gen): s["evs"] = gs["evs"]
            texts = ["\n\n".join(slot_to_text(s) for s in arm) + "\n" for arm in (tuned, copied, steered)]
            if all(val(t) is None for t in texts):
                j = len(triples); paths = []
                for name, t in zip(("tuned", "copied", "steered"), texts):
                    p = out / f"{name}_{j:04d}.txt"; p.write_text(t); paths.append(str(p))
                triples.append(paths)
    val.close()
    novel = 0; tot = 0
    corpus_spreads = {tuple(s["evs"].get(k, 0) for k in STATS) for t in corpus for s in t}
    print(f"{len(triples)} valid triples from {n_teams} real teams", flush=True)
    root = Path("/tmp/vgc-pilot/vgc-bench/teams/reg_mb"); opp = []
    for i in [t["id"] for t in json.load(open("/tmp/vgc-pilot/top50_evs.json"))]:
        for c in (root / f"{i}.txt", root / "featured" / f"{i}.txt"):
            if c.exists(): opp.append(str(c)); break
    files = [p for tr in triples for p in tr]
    print(f"battling {len(files)} teams x 24 vs {len(opp)}", flush=True)
    res = pool.score([(f, opp) for f in files], battles=24, conc=50)
    A = np.array([[res[p]["win_rate"] for p in tr] for tr in triples])
    json.dump({"triples": triples, "results": res}, open("/tmp/vgc-pilot/steer_eval.json", "w"), indent=1)
    names = ["tuned (as played)", "copied (same species)", "steered (bin 5, g=4)"]
    for k, nm in enumerate(names): print(f"{nm:24s} {A[:,k].mean():.4f} ± {A[:,k].std(ddof=1)/np.sqrt(len(A)):.4f}")
    def paired(a, b, lab):
        d = A[:, a] - A[:, b]; se = d.std(ddof=1) / np.sqrt(len(d)); print(f"  {lab:32s} {d.mean():+.4f} ± {se:.4f}  ({d.mean()/se:+.1f} σ)  wins {int((d>0).sum())} / losses {int((d<0).sum())}")
    print("paired differences:"); paired(2, 1, "steered − copied"); paired(2, 0, "steered − tuned"); paired(1, 0, "copied − tuned")

if __name__ == "__main__":
    main()
